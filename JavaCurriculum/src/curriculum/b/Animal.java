package curriculum.b;

public class Animal {
	// 情報の入力
	String name;
	double body;
	int speed;


	// getter,setterの生成
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name = name;
	}
	public double getBody() {
		return body;
	}
	public void setBody(double body) {
		this.body = body;
	}
	public int getSpeed() {
		return speed;
	}
	public void setSpeed(int speed) {
		this.speed = speed;
	}



}
